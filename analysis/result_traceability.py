"""Write the token-to-source traceability table for every manuscript number."""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

BUILD = ROOT / "manuscript" / "build_manuscript.py"
TEMPLATES = [
    ROOT / "manuscript" / "manuscript_template.md",
    ROOT / "supplement" / "supplement_template.md",
]
OUTPUT = ROOT / "docs" / "JRU_RESULT_TRACEABILITY.md"


def token_sources() -> dict[str, str]:
    tree = ast.parse(BUILD.read_text())
    sources: dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name in {
            "replacements", "config_tokens"
        }:
            for sub in ast.walk(node):
                if isinstance(sub, ast.Dict):
                    for key, value in zip(sub.keys, sub.values):
                        if isinstance(key, ast.Constant) and isinstance(key.value, str):
                            sources.setdefault(
                                key.value,
                                " ".join(ast.unparse(value).split()),
                            )
    return sources


def where_used() -> dict[str, list[str]]:
    used: dict[str, list[str]] = {}
    for path in TEMPLATES:
        for number, line in enumerate(path.read_text().splitlines(), 1):
            for token in re.findall(r"\{\{([A-Z0-9_]+)\}\}", line):
                used.setdefault(token, []).append(
                    f"{path.parent.name}/{path.name}:{number}"
                )
    return used


def main() -> None:
    from manuscript.build_manuscript import replacements

    values = replacements()
    sources = token_sources()
    used = where_used()
    lines = [
        "# JRU result traceability",
        "",
        "Generated by `analysis/result_traceability.py`. Every number in the",
        "manuscript and Online Resource 1 enters through a `{{TOKEN}}` in the",
        "templates; this table gives each token's rendered value, the code",
        "expression that produces it (reading `results/manuscript_values.json`,",
        "which `analysis/build_manuscript_assets.py` builds from `results/` and",
        "`analysis/` CSV outputs, or the config), and where it is used. Figure",
        "and table markers and the reference-list marker are excluded.",
        "",
        "| Token | Value | Source expression | Used in |",
        "|---|---|---|---|",
    ]
    missing = []
    for token in sorted(used):
        if token.startswith(("FIGURE_", "TABLE_")) or token == "REFERENCES":
            continue
        if token not in values:
            missing.append(token)
            continue
        source = sources.get(token, "derived in replacements()")
        source = source.replace("|", "\\|")
        if len(source) > 160:
            source = source[:157] + "..."
        value = str(values[token]).replace("|", "\\|")
        lines.append(
            f"| `{token}` | {value} | `{source}` | {', '.join(used[token])} |"
        )
    if missing:
        raise ValueError(f"Template tokens without a value: {missing}")
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote traceability for {len(lines) - 12} tokens", flush=True)


if __name__ == "__main__":
    main()
